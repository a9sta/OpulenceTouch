/** 깊이를 말로 */
export function depthWord(m) {
  if (!m) return '파인 자리가 없습니다';
  if (m < 100) return '손바닥만큼 얕게 팬 정도입니다';
  if (m < 300) return '골목 하나쯤 들어온 깊이입니다';
  if (m < 800) return '한 블록을 넘게 파고든 깊이입니다';
  if (m < 2000) return '걸어서 십 분은 걸릴 만큼 깊습니다';
  if (m < 5000) return '동네 하나가 통째로 들어갈 만큼 깊습니다';
  return '시가지 하나가 들어갈 만큼 깊습니다';
}
/** 겉선 안 땅 비율을 말로 */
export function fillWord(f) {
  if (f >= 98) return '겉선 안이 거의 땅으로 찹니다';
  if (f >= 94) return '겉선 안이 대부분 땅입니다';
  if (f >= 89) return '겉선 안의 열에 한 칸쯤이 빈칸입니다';
  if (f >= 83) return '겉선 안의 여섯 칸 가운데 한 칸이 빈칸입니다';
  if (f >= 74) return '겉선 안의 네 칸 가운데 한 칸 안팎이 빈칸입니다';
  return '겉선 안의 거의 삼분의 일이 빈칸입니다';
}
